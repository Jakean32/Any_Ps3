#!/usr/bin/env python3
"""Generates tests/fixtures/ppu_fixtures.h from GNU-binutils-assembled PPC64
binaries and the disassembly inventory. Regenerate with any powerpc64
assembler (see tests/fixtures/*.s and scripts/regen_ppu_fixtures.sh)."""
import re, subprocess, sys, os

RESEARCH = '/home/z/my-project/research'
OUT = '/home/z/my-project/Any_Ps3/tests/fixtures/ppu_fixtures.h'

# Assembler toolchain resolution: env override, then the persistent in-repo
# tools directory, then the (legacy) research path, then PATH.
def find_ppc64tools():
    import shutil
    candidates = [
        os.environ.get('ANYPS3_PPC_TOOLS', ''),
        '/home/z/my-project/tools/ppc64tools/usr/bin',
        f'{RESEARCH}/ppc64tools/usr/bin',
    ]
    for c in candidates:
        if c and os.path.isfile(os.path.join(c, 'powerpc64-linux-gnu-as')):
            return c
    if shutil.which('powerpc64-linux-gnu-as'):
        return ''
    raise SystemExit(
        'No powerpc64 assembler found. Install without root:\n'
        '  apt-get download binutils-powerpc64-linux-gnu\n'
        '  dpkg-deb -x binutils-powerpc64-linux-gnu_*_amd64.deb /home/z/my-project/tools/ppc64tools')

TOOLS = find_ppc64tools()
_prefix = f'{TOOLS}/' if TOOLS else ''
AS = f'{_prefix}powerpc64-linux-gnu-as'
LD = f'{_prefix}powerpc64-linux-gnu-ld'
OBJDUMP = f'{_prefix}powerpc64-linux-gnu-objdump'
OBJCOPY = f'{_prefix}powerpc64-linux-gnu-objcopy'

# Fixture sources live in the repository.
FIXTURES = '/home/z/my-project/Any_Ps3/tests/fixtures'

def run_tool(cmd, **kw):
    """Run an extracted binutils tool with its bundled shared libraries."""
    env = dict(os.environ)
    if TOOLS:
        libdir = os.path.join(TOOLS, '..', 'lib', 'x86_64-linux-gnu')
        env['LD_LIBRARY_PATH'] = os.path.abspath(libdir) + ':' + env.get('LD_LIBRARY_PATH', '')
    return subprocess.run(cmd, env=env, **kw)

def sections_words(elf):
    """Return [(addr, word)] for executable sections via objdump."""
    d = run_tool([OBJDUMP, '-d', elf], capture_output=True, text=True).stdout
    words = []
    for m in re.finditer(r'^\s*([0-9a-f]+):\t((?:[0-9a-f]{2} ){1,4})\t(\S+)', d, re.M):
        addr = int(m.group(1), 16)
        b = bytes.fromhex(m.group(2).replace(' ', ''))
        for i in range(0, len(b), 4):
            words.append((addr + i, int.from_bytes(b[i:i+4], 'big')))
    return words

def section_bytes(elf, sec):
    out = f'/tmp/sec_{sec}.bin'
    run_tool([OBJCOPY, '-O', 'binary', f'--only-section={sec}', elf, out], check=True)
    data = open(out, 'rb').read()
    os.remove(out)
    return data

def sec_addr(elf, sec):
    d = run_tool([OBJDUMP, '-h', elf], capture_output=True, text=True).stdout
    for line in d.splitlines():
        parts = line.split()
        if len(parts) > 3 and parts[1] == sec:
            return int(parts[3], 16)
    return 0

def build(name):
    src = f'{FIXTURES}/{name}.s'
    obj = f'/tmp/{name}.o'
    elf = f'/tmp/{name}.elf'
    run_tool([AS, '-mregnames', '-o', obj, src], check=True)
    run_tool([LD, '-Ttext=0x10000', '-Tdata=0x11000', '-e', '0x10000', '-o', elf, obj],
         check=True, capture_output=True)
    return elf

def hex_lines(data, indent='    '):
    out = []
    for i in range(0, len(data), 16):
        chunk = ', '.join(f'0x{b:02x}' for b in data[i:i+16])
        out.append(indent + chunk + ',')
    return '\n'.join(out)

h = []
h.append('// AUTO-GENERATED by research/gen_fixtures.py — do not edit by hand.')
h.append('// PPC64 big-endian machine code produced by GNU binutils 2.44')
h.append('// (powerpc64-linux-gnu-as). Regenerate: scripts/regen_ppu_fixtures.sh')
h.append('#pragma once')
h.append('#include <cstdint>')
h.append('#include <cstddef>')
h.append('')

def carry_over(name, kind, old):
    """Reuse a previously generated array when the .s source is not present
    (fp/vmx/sync/threads sources predate the repository restructure; their
    compiled bytes were produced by the same binutils 2.44 pipeline)."""
    if not old:
        return None
    m = re.search(rf'inline constexpr unsigned char k{name}_{kind}\[\] = \{{(.*?)\}};', old, re.S)
    return m.group(1) if m else None

OLD_H = open(OUT).read() if os.path.exists(OUT) else ''

for name, desc in [('hello', 'PS3 homebrew hello world (sys_tty_write + exit)'),
                   ('alu', 'ALU/rotate semantic tests'),
                   ('branch', 'conditional-branch + bdnz loop tests'),
                   ('fp', 'floating-point semantic tests (double+single)'),
                   ('vmx', 'VMX/AltiVec subset semantic tests'),
                   ('sync', 'lwarx/stwcx/ldarx/stdcx reservation tests'),
                   ('threads', 'PPU thread create/join with cross-thread reservations'),
                   ('module', 'PS3-style module: OPD entry, sysPrxForUser NID import via PowerOpen stub, unknown-NID ENOSYS')]:
    src_path = f'{FIXTURES}/{name}.s'
    if os.path.isfile(src_path):
        elf = build(name)
        text = section_bytes(elf, '.text')
        data = section_bytes(elf, '.data')
        taddr, daddr = sec_addr(elf, '.text'), sec_addr(elf, '.data')
    else:
        text = carry_over(name, 'text', OLD_H)
        data = carry_over(name, 'data', OLD_H)
        m_t = re.search(rf'inline constexpr unsigned k{name}_text_addr = 0x([0-9a-f]+);', OLD_H)
        m_d = re.search(rf'inline constexpr unsigned k{name}_data_addr = 0x([0-9a-f]+);', OLD_H)
        if text is None or data is None or not m_t or not m_d:
            raise SystemExit(f'fixture source missing and no previous bytes to carry over: {name}.s')
        taddr, daddr = int(m_t.group(1), 16), int(m_d.group(1), 16)
        desc += ' (carried over from a previous binutils-2.44 build; source .s archived in releases)'
    h.append(f'// {desc}')
    h.append(f'inline constexpr unsigned char k{name}_text[] = {{')
    h.append(text if isinstance(text, str) else hex_lines(text))
    h.append('};')
    h.append(f'inline constexpr size_t k{name}_text_size = sizeof(k{name}_text);')
    h.append(f'inline constexpr unsigned k{name}_text_addr = 0x{taddr:08x};')
    h.append(f'inline constexpr unsigned char k{name}_data[] = {{')
    h.append(data if isinstance(data, str) else hex_lines(data))
    h.append('};')
    h.append(f'inline constexpr unsigned k{name}_data_addr = 0x{daddr:08x};')
    h.append('')

# Complete hello ELF (the built-in demo binary; also shipped as
# hosts/android/app/src/main/assets/hello.elf and windows samples/hello.elf).
elf_bytes = open('/home/z/my-project/Any_Ps3/hosts/android/app/src/main/assets/hello.elf', 'rb').read()
h.append('inline constexpr unsigned char khello_elf[] = {')
h.append(hex_lines(elf_bytes))
h.append('};')
h.append('inline constexpr size_t khello_elf_size = sizeof(khello_elf);')
h.append('')

# Full instruction inventory for decoder validation
inv = open(f'{RESEARCH}/inventory.dump').read()
try:
    inv += open(f'{RESEARCH}/fp_vmx_inventory.dump').read()
except FileNotFoundError:
    pass
h.append('// Full binutils instruction inventory: (word, mnemonic) pairs to validate the')
h.append('// decoder against ground truth. Mnemonics map 1:1 onto anyps3::Mn variants.')
h.append('struct PpuDecodeRow { uint32_t word; const char* name; };')
h.append('inline constexpr PpuDecodeRow kPpuDecodeInventory[] = {')
for m in re.finditer(r'^\s*[0-9a-f]+:\t((?:[0-9a-f]{2} ){4})\t(\S+)', inv, re.M):
    w = int.from_bytes(bytes.fromhex(m.group(1).replace(' ', '')), 'big')
    h.append(f'    {{0x{w:08x}u, "{m.group(2)}"}},')
h.append('};')
h.append('inline constexpr size_t kPpuDecodeInventoryCount =')
h.append('    sizeof(kPpuDecodeInventory) / sizeof(PpuDecodeRow);')
h.append('')

open(OUT, 'w').write('\n'.join(h) + '\n')
print(f'wrote {OUT}: {len(h)} lines')
