#!/usr/bin/env python3
"""Generate core/include/anyps3/hle/syscall_names.h from the verified LV2
syscall table (tools/reference/syscall_table.txt — researched in earlier
phases, format: "<number> <name>" per line).

Only name facts are used; the lookup makes the honest ENOSYS logs human
readable ("LV2 syscall 461 (_sys_prx_get_module_id_by_address) not
implemented") which is what the user's bring-up reports rely on.

Regenerate:  python3 tools/reference/gen_syscall_names.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'tools', 'reference', 'syscall_table.txt')
OUT = os.path.join(ROOT, 'core', 'include', 'anyps3', 'hle', 'syscall_names.h')

pairs = []
for line in open(SRC):
    m = re.match(r'\s*(\d+)\s+([A-Za-z_][A-Za-z0-9_]*)', line)
    if m:
        n, name = int(m.group(1)), m.group(2)
        if not pairs or pairs[-1][0] != n:
            pairs.append((n, name))
pairs.sort()

h = []
h.append('// AUTO-GENERATED by tools/reference/gen_syscall_names.py — do not edit.')
h.append('// Source: tools/reference/syscall_table.txt (verified LV2 syscall numbers).')
h.append('#pragma once')
h.append('#include <cstdint>')
h.append('')
h.append('namespace anyps3 {')
h.append('')
h.append('inline const char* Lv2SyscallName(uint32_t nr) {')
h.append('    switch (nr) {')
h.append('    default: return nullptr;')
for n, name in pairs:
    h.append(f'    case {n}: return "{name}";')
h.append('    }')
h.append('}')
h.append('')
h.append('}  // namespace anyps3')
open(OUT, 'w').write('\n'.join(h) + '\n')
print(f'wrote {OUT}: {len(pairs)} syscall names')
